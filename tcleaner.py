#!/data/data/com.termux/files/usr/bin/env python
import os
import shutil
import sys
from pathlib import Path
from typing import List, Tuple

PREFIX: Path = Path(os.environ.get("PREFIX", "/data/data/com.termux/files/usr"))
HOME: Path = Path.home()
CFG: Path = PREFIX / "etc" / "dpkg" / "dpkg.cfg.d" / "99-termux-slim"

STRIP: List[Path] = [
    PREFIX / "share" / "man",
    PREFIX / "share" / "doc",
    PREFIX / "share" / "info",
    PREFIX / "share" / "gtk-doc",
    PREFIX / "share" / "help",
    PREFIX / "share" / "applications",
    PREFIX / "share" / "desktop-directories",
    PREFIX / "share" / "icons",
    PREFIX / "share" / "pixmaps",
    PREFIX / "share" / "sounds",
    PREFIX / "share" / "themes",
    PREFIX / "share" / "mime",
    PREFIX / "share" / "locale",
]

CACHE_DIRS: List[Path] = [
    PREFIX / "var" / "cache" / "apt" / "archives",
    PREFIX / "tmp",
    HOME / ".cache",
]

KEEP: List[Path] = [
    HOME / ".cache" / "pip" / "wheels",
]


def human(kib: int) -> str:
    if kib >= 1048576:
        return f"{kib / 1048576:.2f} GB"
    if kib >= 1024:
        return f"{kib / 1024:.1f} MB"
    return f"{kib} KB"


def tree_size_kib(p: Path) -> int:
    try:
        st = p.lstat()
    except OSError:
        return 0
    total = st.st_size
    if p.is_symlink() or not p.is_dir():
        return total // 1024
    for dirpath, dirnames, filenames in os.walk(p, followlinks=False):
        for name in filenames:
            try:
                total += os.lstat(os.path.join(dirpath, name)).st_size
            except OSError:
                pass
        for dn in dirnames:
            try:
                total += os.lstat(os.path.join(dirpath, dn)).st_size
            except OSError:
                pass
    return total // 1024


def collect(root: Path, keep: List[Path]) -> List[Path]:
    out: List[Path] = []
    if not root.is_dir():
        return out
    try:
        entries = list(os.scandir(root))
    except OSError:
        return out
    for entry in entries:
        child = Path(entry.path)
        if any(child == k for k in keep):
            continue
        if any(k != child and k.is_relative_to(child) for k in keep):
            out.extend(collect(child, keep))
            continue
        out.append(child)
    return out


def sorted_by_size(paths: List[Path]) -> List[Tuple[int, Path]]:
    sized = [(tree_size_kib(p), p) for p in paths]
    sized.sort(key=lambda t: (t[0], str(t[1])))
    return sized


def main(argv: List[str]) -> int:
    apply = False
    for a in argv[1:]:
        if a == "--apply":
            apply = True
        elif a in ("-h", "--help"):
            print(f"usage: {Path(argv[0]).name} [--apply]")
            return 0
        else:
            print(f"unknown arg: {a}", file=sys.stderr)
            return 2

    if not PREFIX.is_dir():
        print(f"not a Termux prefix: {PREFIX}", file=sys.stderr)
        return 1

    deletable: List[Path] = []
    for root in (*STRIP, *CACHE_DIRS):
        deletable.extend(collect(root, KEEP))

    kept_present = [k for k in KEEP if k.exists()]
    sized = sorted_by_size(deletable)
    total_kib = sum(kb for kb, _ in sized)

    print("kept (will not be touched):")
    if kept_present:
        for kb, p in sorted_by_size(kept_present):
            print(f"  {human(kb):>10}  {p}")
    else:
        print("  (none present yet)")

    print()
    print(f"delete candidates — {len(sized)} items, {human(total_kib)}:")
    for kb, p in sized:
        print(f"  {human(kb):>10}  {p}")
    print()
    print(f"total reclaimable: {human(total_kib)}")

    if not apply:
        print("dry run — rerun with --apply to execute")
        return 0

    CFG.parent.mkdir(parents=True, exist_ok=True)
    cfg_lines = ["# generated by termux-slim"]
    for d in STRIP:
        cfg_lines.append(f"path-exclude={d}/*")
    CFG.write_text("\n".join(cfg_lines) + "\n", encoding="utf-8")
    print(f"wrote {CFG}")

    for _kb, p in sized:
        try:
            if p.is_symlink() or not p.is_dir():
                p.unlink()
            else:
                shutil.rmtree(p)
        except OSError as e:
            print(f"  warn: {p}: {e}", file=sys.stderr)

    print(f"done. reclaimed ~{human(total_kib)}")
    print(f"revert: rm {CFG} && pkg upgrade --reinstall")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
