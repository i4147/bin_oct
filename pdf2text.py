#!/data/data/com.termux/files/usr/bin/env python
"""Write a self-contained prompt that instructs an AI coding agent to build a Python command-line tool for extracting text from PDF files. The tool should:

**Purpose:** Convert a PDF file into plain text, either as a single concatenated text file or as one text file per page in a separate output directory.

**Inputs:**
- A path to a PDF file (required positional argument).
- An extraction engine selector with two choices: a PyPDF2-based engine and a pdfplumber-based engine. The engine name should be matched case-sensitively in lowercase, and any other value must raise a ValueError with a message of the form "Unsupported engine: <name>".
- A text encoding option (applies to output files and, where supported, to pdfplumber's extraction call).
- A mode selector: concatenate all pages into one output file, or split into per-page files.
- An optional output path override for each mode.

**Outputs:**
- Concatenate mode: a single text file. By default, the output path is the input path with the ".pdf" extension replaced by ".txt" (the replacement should be done on the string form of the path).
- Split mode: a directory containing one text file per page, with the default directory derived from the PDF path (for example, the PDF's stem with a suffix, placed alongside the PDF). Page files should be numbered with zero-padded indices so they sort correctly.

**Implementation requirements:**
- Use `from __future__ import annotations` and type hints throughout, using `Path`, `Iterator`, and `Optional` from `typing`.
- Use `argparse` for the command-line interface, and `sys` for exit codes and error output.
- Implement page extraction as generator functions using `yield from`, so pages are processed lazily.
- For PyPDF2: open the file in binary mode, create a `PdfReader`, and yield each page's `extract_text()` result, substituting an empty string when the result is None.
- For pdfplumber: open the file with `pdfplumber.open`, iterate pages, and call `extract_text(encoding=...)`. If that call raises a TypeError (the installed version doesn't accept the argument), fall back to calling `extract_text()` with no arguments. Substitute an empty string for None results.
- Import the engine libraries lazily inside their helper functions so that a missing library only fails when that engine is selected.
- Write text files with `Path.write_text` using the specified encoding.
- Provide a top-level dispatcher that selects the engine helper and raises ValueError for unknown engines.
- Use a `main` function returning an integer exit code, invoked under the standard `if __name__ == "__main__":` guard with `sys.exit`.
- The shebang line should point to the Termux Python interpreter path (`/data/data/com.termux/files/usr/bin/env python`).

**Error handling and edge cases:**
- Validate that the PDF path exists and is a file before processing; on failure, print a clear message to stderr and return a nonzero exit code.
- Handle the case where the output file or directory already exists or cannot be created, reporting errors to stderr and returning nonzero.
- Handle empty pages (no extractable text) by writing empty content rather than failing.
- Handle a PDF filename that does not end in ".pdf" in the default output derivation sensibly (the replacement simply does nothing in that case).
- Catch exceptions from the extraction libraries and missing-dependency import errors, reporting an actionable message that names the library to install (PyPDF2 or pdfplumber).
- Ensure the split output directory is created with parent directories as needed.

**Usage details:**
- The script should be runnable directly as an executable file and should print a brief summary on success, such as the number of pages processed and the output location.
- Include a `--help` description generated by argparse that documents each option.

**Dependencies:** Python 3 standard library, plus either PyPDF2 or pdfplumber depending on the chosen engine. No other third-party packages should be required.

Produce the complete script as a single file that follows these requirements exactly.
---"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Iterator, Optional


def _extract_pages_pypdf2(pdf_path: Path) -> Iterator[str]:
    import PyPDF2

    with pdf_path.open("rb") as fh:
        reader = PyPDF2.PdfReader(fh)
        for page in reader.pages:
            text = page.extract_text()
            yield text or ""


def _extract_pages_pdfplumber(pdf_path: Path, encoding: str) -> Iterator[str]:
    import pdfplumber

    with pdfplumber.open(pdf_path) as pdf:
        for page in pdf.pages:
            try:
                text = page.extract_text(encoding=encoding)
            except TypeError:
                text = page.extract_text()
            yield text or ""


def extract_pages(pdf_path: Path, engine: str, encoding: str) -> Iterator[str]:
    if engine == "pypdf2":
        yield from _extract_pages_pypdf2(pdf_path)
    elif engine == "pdfplumber":
        yield from _extract_pages_pdfplumber(pdf_path, encoding)
    else:
        msg = f"Unsupported engine: {engine}"
        raise ValueError(msg)


def write_text(path: Path, text: str, encoding: str) -> None:
    path.write_text(text, encoding=encoding)


def default_concat_output(pdf_path: Path) -> Path:
    return Path(str(pdf_path).replace(".pdf", ".txt"))


def default_split_output_dir(pdf_path: Path) -> Path:
    return Path(pdf_path.stem)


def concat_text(
    pdf_path: Path,
    output: Optional[Path],
    engine: str,
    encoding: str,
    quiet: bool,
) -> int:
    if output is None:
        output = default_concat_output(pdf_path)
    text = "".join(extract_pages(pdf_path, engine, encoding))
    write_text(output, text, encoding)
    if not quiet:
        print(f"Text extracted and saved to {output}")
    return 0


def split_text(
    pdf_path: Path,
    output_dir: Optional[Path],
    engine: str,
    encoding: str,
    pad_width: int,
    parents: bool,
    quiet: bool,
) -> int:
    if pad_width < 1:
        msg = "--pad-width must be at least 1"
        raise ValueError(msg)
    if output_dir is None:
        output_dir = default_split_output_dir(pdf_path)
    output_dir.mkdir(parents=parents, exist_ok=True)
    for page_number, text in enumerate(
        extract_pages(pdf_path, engine, encoding),
        start=1,
    ):
        page_str = f"{page_number:0{pad_width}d}"
        out_path = output_dir / f"{pdf_path.stem}{page_str}.txt"
        write_text(out_path, text, encoding)
        if not quiet:
            print(f"{out_path} created")
    return 0


def run_concat(args: argparse.Namespace) -> int:
    return concat_text(
        pdf_path=args.pdf,
        output=args.output,
        engine=args.engine,
        encoding=args.encoding,
        quiet=args.quiet,
    )


def run_split(args: argparse.Namespace) -> int:
    return split_text(
        pdf_path=args.pdf,
        output_dir=args.output_dir,
        engine=args.engine,
        encoding=args.encoding,
        pad_width=args.pad_width,
        parents=args.parents,
        quiet=args.quiet,
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="pdf_text_extractor.py",
        description="Extract text from PDF files using PyPDF2 or pdfplumber.",
    )
    subparsers = parser.add_subparsers(
        dest="command",
        required=True,
        help="Extraction mode",
    )
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument(
        "pdf",
        type=Path,
        help="Path to the input PDF file.",
    )
    common.add_argument(
        "--encoding",
        default="utf-8",
        help="Text encoding used when writing output files. Default: utf-8",
    )
    common.add_argument(
        "--quiet",
        action="store_true",
        help="Suppress progress messages.",
    )
    common.add_argument(
        "--engine",
        choices=("pypdf2", "pdfplumber"),
        help=("PDF extraction engine. Defaults: pypdf2 for concat, pdfplumber for split."),
    )
    concat = subparsers.add_parser(
        "concat",
        parents=[common],
        help="Extract all pages into a single text file.",
    )
    concat.add_argument(
        "-o",
        "--output",
        type=Path,
        default=None,
        help=("Output .txt file. Default: input path with .pdf replaced by .txt."),
    )
    concat.set_defaults(func=run_concat, engine="pypdf2")
    split = subparsers.add_parser(
        "split",
        parents=[common],
        help="Extract each page into its own text file.",
    )
    split.add_argument(
        "-d",
        "--output-dir",
        type=Path,
        default=None,
        help=("Directory for per-page text files. Default: directory named after the PDF stem."),
    )
    split.add_argument(
        "--pad-width",
        type=int,
        default=3,
        help="Minimum page-number width. Default: 3 (001, 002, ...).",
    )
    split.add_argument(
        "--parents",
        action="store_true",
        help="Create parent directories for --output-dir if needed.",
    )
    split.set_defaults(func=run_split, engine="pdfplumber")
    return parser


def main(argv: Optional[list[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if not args.pdf.is_file():
        parser.error(f"PDF file not found: {args.pdf}")
    try:
        return args.func(args)
    except ImportError as exc:
        print(
            f"Missing dependency: {exc}. Install with: pip install PyPDF2 pdfplumber",
            file=sys.stderr,
        )
        return 1
    except Exception as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
